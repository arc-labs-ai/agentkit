"""JsonSchemaAdapter — adapter over a raw JSON Schema dict.

The escape hatch. When a user has a schema that isn't a Python type (it came from
an OpenAPI spec, was generated by a sibling service, or describes a shape they
don't want to mirror in code), they should still be able to declare it as the
agent's output. This adapter takes the dict *verbatim* and returns ``dict``
instances on parse — no type stamping.

Raw JSON schemas use the same canonical validator as CallRuntime. Missing
validation dependencies fail at adapter construction, before model dispatch;
provider-side structured modes cannot replace host validation."""

from __future__ import annotations

import json
from typing import Any, cast

from agentkit.core.serialization._immutable import deep_freeze, thaw
from agentkit.models.contracts.schema import validate_output, validate_schema
from agentkit.models.output.protocol import OutputCoercionError


class JsonSchemaAdapter:
    """Adapter over a raw JSON Schema dict. ``python_type`` is ``dict`` because
    that *is* the type instances are coerced into — there is no Python class
    associated with the schema."""

    python_type: type = dict
    """Always ``dict`` — the raw-schema flavour deliberately does not stamp a
    Python class. Callers who want a typed result should use one of the other
    adapters."""

    def __init__(self, schema: dict[str, Any], *, name: str | None = None) -> None:
        if not isinstance(schema, dict):
            raise TypeError(f"JsonSchemaAdapter expects a dict, got {type(schema).__name__}")
        if schema.get("type") != "object":
            # We could in principle support top-level arrays / primitives, but
            # provider structured-output modes universally expect an object at
            # the top level — refusing here surfaces the mismatch at build time.
            raise TypeError(
                "JsonSchemaAdapter requires a top-level object schema "
                "(`type: 'object'`); other top-level types are not supported"
            )
        validate_schema(schema)
        self._schema = deep_freeze(schema)
        self.name: str = name or schema.get("title") or "Output"
        """Defaults to the schema's ``title`` if present, else a bland ``"Output"``
        — raw dicts have no class name to fall back on, so the caller is
        encouraged to pass ``name=`` when registering one."""

    def json_schema(self) -> dict[str, Any]:
        """Return an independent mutable wire schema from the frozen canonical contract."""
        return cast(dict[str, Any], thaw(self._schema))

    def parse(self, raw: str | dict[str, Any]) -> dict[str, Any]:
        """JSON-decode and validate against the canonical host schema."""
        if isinstance(raw, str):
            try:
                payload = json.loads(raw)
            except json.JSONDecodeError as e:
                raise OutputCoercionError(
                    f"response is not valid JSON: {e.msg} (line {e.lineno}, col {e.colno})",
                    raw=raw,
                    errors=[f"json: {e.msg}"],
                ) from e
        else:
            payload = raw
        if not isinstance(payload, dict):
            raise OutputCoercionError(
                f"expected a JSON object for {self.name}, got {type(payload).__name__}",
                raw=raw,
                errors=[f"top-level: expected object, got {type(payload).__name__}"],
            )
        try:
            return self.validate(payload)
        except OutputCoercionError as exc:
            exc.raw = raw
            raise

    def partial_parse(self, raw: str) -> dict[str, Any] | None:
        """Tolerant parse → return the partial dict as-is.

        No further coercion is done — the raw-schema flavour returns
        ``dict`` instances on full parse, and the same convention
        applies mid-stream. Schema validation is intentionally skipped
        on the partial: a half-streamed object would routinely violate
        ``required``, and the strict terminal parse is the source of
        truth for conformance.
        """
        from agentkit.models.output._partial_json import parse_partial

        try:
            data = parse_partial(raw)
        except Exception:
            return None
        if not isinstance(data, dict):
            return None
        return data

    def serialize(self, value: dict[str, Any]) -> dict[str, Any]:
        """Identity — the value already IS the dict. Returned as-is rather than
        deep-copied because the durable store treats serialized output as
        owned-by-store after the call returns."""
        return value

    def validate(self, value: Any) -> dict[str, Any]:
        """Validate an arbitrary Python value against the raw JSON Schema.

        The value must be an object, and every terminal parse/validation uses
        the canonical host validator. Provider-side guarantees do not replace
        host validation and missing dependencies never weaken the contract.
        """
        if not isinstance(value, dict):
            raise OutputCoercionError(
                f"value of type {type(value).__name__} is not a JSON object for {self.name}",
                raw=repr(value),
                errors=[f"top-level: expected object, got {type(value).__name__}"],
            )
        try:
            return validate_output(value, self._schema)  # type: ignore[no-any-return]
        except ImportError:
            raise
        except Exception as exc:
            path = ".".join(str(part) for part in getattr(exc, "absolute_path", ())) or "<root>"
            message = str(getattr(exc, "message", exc))
            raise OutputCoercionError(
                f"value failed schema validation at {path}: {message}",
                raw=value,
                errors=[f"{path}: {message}"],
            ) from exc
